struct DbValue final
{
    std::string sval;
    int64_t ival = 0;

    DbValue() = default;
    ~DbValue() = default;

    DbValue(const std::string& s, int64_t i)
        : sval(s)
        , ival(i)
    {}
    DbValue(int64_t i, const std::string& s)
        : sval(s)
        , ival(i)
    {}
    DbValue(int64_t i)
        : ival(i)
    {}
    DbValue(const std::string& s)
        : sval(s)
    {}

    inline bool empty() const { return 0 == ival && sval.empty(); }
};

